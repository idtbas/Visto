// Compiles asm/kernel.ts to WebAssembly and embeds it as base64 in src/sim/brain/kernel.wasm.ts
const { execFileSync } = require('node:child_process');
const fs = require('node:fs');
const path = require('node:path');
const root = path.join(__dirname, '..');
fs.mkdirSync(path.join(root, 'out'), { recursive: true });
const wasm = path.join(root, 'out', 'kernel.wasm');
execFileSync(process.execPath, [path.join(root, 'node_modules', 'assemblyscript', 'bin', 'asc.js'), path.join(root, 'asm', 'kernel.ts'), '-o', wasm, '-O3', '--enable', 'simd', '--runtime', 'stub', '--noAssert'], { stdio: 'inherit' });
const bytes = fs.readFileSync(wasm);
fs.writeFileSync(
  path.join(root, 'src', 'sim', 'brain', 'kernel.wasm.ts'),
  `// generated by tools/build-kernel.cjs from asm/kernel.ts – do not edit\nexport const KERNEL_WASM = '${bytes.toString('base64')}';\n`,
);
console.log(`kernel.wasm ${bytes.length} bytes`);
